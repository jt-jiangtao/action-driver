import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { parse } = createRequire(join(root, 'apps/agent-runtime/package.json'))('yaml')
const owners = { documents: 'documents', pdf: 'pdf', presentations: 'presentations', spreadsheets: 'spreadsheets', 'skill-creator': 'skills', imagegen: 'image-generation' }
for (const [id, owner] of Object.entries(owners)) {
  const packageRoot = join(root, 'plugins', owner)
  const prefix = `skills/${id}`
  const content = await readFile(join(packageRoot, prefix, 'SKILL.md'), 'utf8')
  const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  const metadata = frontmatter ? parse(frontmatter[1]) : {}
  const list = async path => (await Promise.all((await readdir(join(packageRoot, path), { withFileTypes: true })).map(entry => entry.isDirectory() ? list(`${path}/${entry.name}`) : `${path}/${entry.name}`))).flat()
  const skill = { id, name: metadata.name || id, description: metadata.description || id, resources: (await list(prefix)).sort() }
  await writeFile(join(packageRoot, 'src/skill.ts'), `// Generated by scripts/sync-plugin-skills.mjs; edit skills/${id}/ instead.\nimport type { SkillContribution } from '@actiondriver/plugin-sdk'\nimport content from '../skills/${id}/SKILL.md?raw'\nexport const skill: SkillContribution = { ...${JSON.stringify(skill, null, 2)}, content }\n`)
}
